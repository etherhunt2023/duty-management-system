}

final employeeViewModelProvider = StateNotifierProvider<EmployeeViewModel, AsyncValue<List<Employee>>>((ref) {
  final supabaseService = ref.watch(supabaseServiceProvider);
  return EmployeeViewModel(supabaseService);
});
